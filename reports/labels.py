class Words:
    """Says things in one language."""

    def __init__(self, language=DEFAULT_LANGUAGE):
        self.language = language if language in LANGUAGES else DEFAULT_LANGUAGE
        self._text = TEXT[self.language]

    def t(self, key, **values):
        text = self._text[key]
        return text.format(**values) if values else text

    def all(self):
        return self._text

    def digits(self, text):
        return text.translate(_BANGLA_DIGITS) if self.language == 'bn' else text

    def count(self, number):
        return self.digits(f'{number:,}')

    def date(self, day, short=False):
        months = SHORT_MONTHS if short else MONTHS
        return self.digits(f'{day.day} {months[self.language][day.month - 1]} {day.year}')

    def moment(self, when):
        local = timezone.localtime(when)
        hour = local.hour % 12 or 12
        clock = self.digits(f'{hour}:{local.minute:02d}') + (' AM' if local.hour < 12 else ' PM')
        return f'{self.date(local.date())}, {clock}'

    def period(self, date_from, date_to):
        return self.t('period.to', start=self.date(date_from), end=self.date(date_to))

    def amount(self, amount_minor, currency):
        """The number alone, for a table that names its currency once: '1,234.50'."""
        return self.digits(f'{to_major(amount_minor, currency):,.{currency_exponent(currency)}f}')

    def money(self, amount_minor, currency):
        return f'{currency} {self.amount(amount_minor, currency)}'

    def share(self, fraction):
        return self.digits(f'{fraction * 100:.1f}') + '%'
